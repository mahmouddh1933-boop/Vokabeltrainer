/* Generate the six-unit offline book from reviewed, unit-scoped source content. */
const fs = require("node:fs"),
  path = require("node:path"),
  crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
const parts = Array.from({ length: 6 }, (_, i) =>
  JSON.parse(
    fs.readFileSync(
      path.join(root, `data/book-youth-two-part-one/unit-${i + 1}.json`),
      "utf8",
    ),
  ),
);
const units = parts.map((p) => p.unit),
  activities = parts.flatMap((p) => p.activities),
  sources = parts.flatMap((p) => p.sources);
const contents = JSON.parse(
  fs.readFileSync(
    path.join(root, "data/book-youth-two-part-one/contents.json"),
    "utf8",
  ),
);
const tocActivities = activities.filter((a) => a.source === "photo-37");
sources.push({
  photo: "photo-37",
  file: contents.file,
  page: null,
  unit: null,
  topics: ["فهرس الوحدات الست", "الأصوات والقواعد"],
  blocks: tocActivities.map((a) => ({ title: a.title, activities: [a.id] })),
});
for (const s of sources) {
  if (s.page !== null) s.page = String(s.page);
}
for (const a of activities) {
  if (a.sourcePage !== null) a.sourcePage = String(a.sourcePage);
}
for (const s of sources)
  s.blocks = s.blocks.flatMap((b) =>
    b.activities.map((id) => ({ title: b.title, activity: id })),
  );
const existing = [
  "letter-data",
  "practice-data",
  "book-two-data",
  "youth-data",
  "youth-two-data",
].reduce(
  (map, name) =>
    Object.assign(
      map,
      require(path.join(root, "js", name + ".js")).audio || {},
    ),
  {},
);
const audio = {},
  clips = [];
function voice(text) {
  text = text.normalize("NFC");
  if (audio[text]) return;
  if (existing[text]) audio[text] = existing[text];
  else {
    const file =
      "audio/book-youth-two-part-one/" +
      crypto.createHash("sha256").update(text).digest("hex").slice(0, 14) +
      ".mp3";
    audio[text] = file;
    clips.push({ text, path: file });
  }
}
function chunks(text) {
  const words = text.split(/\s+/);
  let line = "",
    lines = [];
  for (const word of words) {
    if (line.length + word.length + 1 > 180) {
      lines.push(line);
      line = "";
    }
    line += (line ? " " : "") + word;
  }
  if (line) lines.push(line);
  return lines;
}
for (const a of activities) {
  for (const turn of a.dialogue || []) voice(turn.text);
  for (const word of a.vocabulary || []) voice(word.ar);
  if (a.passage) {
    a.passageLines = a.passage.split("\n").flatMap(chunks);
    a.passageLines.forEach(voice);
  }
  for (const q of a.tasks)
    if (q.audioText) {
      const text = q.audioText.normalize("NFC");
      if (!existing[text])
        throw new Error("Missing existing listening clip " + text);
      audio[text] = existing[text];
    }
}
if (sources.length !== 37 || new Set(sources.map((s) => s.photo)).size !== 37)
  throw new Error("All 37 photos required");
for (const a of activities) {
  if (!units.some((u) => u.number === a.unit)) throw new Error("Wrong unit");
  if (!sources.some((s) => s.photo === a.source))
    throw new Error("Unknown source " + a.source);
}
const catalog = JSON.stringify({ units, sources, activities, audio }, null, 2);
fs.writeFileSync(
  path.join(root, "js/youth-book-two-part-one-data.js"),
  `// Generated by tools/build-youth-book-two-part-one.js.\n(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory(require('./youth-two-data.js'));else root.ArabicYouthBookTwoPartOneData=factory(root.ArabicYouthTwoData);})(typeof window!=='undefined'?window:globalThis,function(engine){'use strict';const catalog=${catalog};return {...engine,...catalog};});\n`,
);
fs.mkdirSync(path.join(root, "audio/book-youth-two-part-one"), {
  recursive: true,
});
fs.writeFileSync(
  path.join(root, "audio/book-youth-two-part-one-manifest.json"),
  JSON.stringify(
    {
      voice:
        "Synthetic Arabic Google Translate TTS, verified HTTPS, 2026-10-21",
      clips,
    },
    null,
    2,
  ) + "\n",
);
const lines = [
  "# كتاب الشباب2 ج1 · تغطية الوحدات والصور",
  "",
  "نصوص وتمارين جديدة وفق موضوعات الصور والفهرس؛ الصور الأصلية لا توزع مع التطبيق.",
  "",
  "| الوحدة | العنوان | الصفحات | القاعدة | الأصوات |",
  "| --- | --- | --- | --- | --- |",
];
for (const u of units)
  lines.push(
    `| ${u.number} | ${u.title} | ${u.pages.join("–")} | ${u.grammar} | ${u.sounds.join("/")} |`,
  );
lines.push(
  "",
  "| الصورة | الملف | الوحدة | صفحة الكتاب | النشاط المشابه |",
  "| --- | --- | --- | --- | --- |",
);
for (const s of sources)
  lines.push(
    `| ${s.photo} | ${s.file} | ${s.unit || "الفهرس"} | ${s.page || "الفهرس"} | ${s.blocks.map((b) => b.title + " (" + b.activity + ")").join("؛ ")} |`,
  );
lines.push(
  "",
  `٦ وحدات، ${sources.length} صورة، ${activities.length} نشاطًا، ${activities.reduce((n, a) => n + a.tasks.length, 0)} سؤالًا ومهمة.`,
  "",
  "أضيفت قواعد الفهرس صراحة حتى حين تعرض صفحات الوحدة تراكيب تطبيقية دون فصل نحوي مستقل. الكتابة والمحادثة الحرة لها نماذج وتقييم ذاتي مستقل عن التصحيح الآلي.",
  "",
);
fs.writeFileSync(
  path.join(root, "docs/YOUTH-BOOK-TWO-PART-ONE-COVERAGE.md"),
  lines.join("\n"),
);
console.log(
  `6 units; ${sources.length} sources; ${activities.length} activities; ${activities.reduce((n, a) => n + a.tasks.length, 0)} tasks; ${clips.length} new MP3s`,
);
