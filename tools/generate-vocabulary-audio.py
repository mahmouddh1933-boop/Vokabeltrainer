"""Bundle exact, vocalization-sensitive audio for every built-in vocabulary entry.

Reuses existing verified lesson recordings. Downloads are only needed to build;
playback uses local MP3 files. Raw synthesis responses are cached outside the repo.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess
import time
import unicodedata
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--workers', type=int, default=5)
parser.add_argument('--cache', type=Path, default=Path('/tmp/olive-vocabulary-audio-cache'))
args = parser.parse_args()
args.cache.mkdir(parents=True, exist_ok=True)
(ROOT/'audio/vocabulary').mkdir(exist_ok=True)
catalog = json.loads((ROOT/'data/vocab_catalog.json').read_text())
texts = sorted({unicodedata.normalize('NFC',w['ar']) for item in catalog['lists'] for w in item['words']})
existing = {}
revision = ROOT/'audio/letter-pronunciation-revision.json'
sources = ([revision] if revision.exists() else []) + sorted((ROOT/'audio').glob('*manifest.json'))
for manifest in sources:
    if manifest.name == 'vocabulary-manifest.json': continue
    for clip in json.loads(manifest.read_text()).get('clips',[]):
        if 'text' in clip and 'path' in clip and (ROOT/clip['path']).is_file():
            existing.setdefault(unicodedata.normalize('NFC',clip['text']),clip['path'])

def make(text):
    key = hashlib.sha256(text.encode()).hexdigest()[:16]
    relative = existing.get(text, f'audio/vocabulary/{key}.mp3')
    target = ROOT/relative
    if not target.exists():
        raw = args.cache/f'{key}.mp3'
        if not raw.exists():
            query = urllib.parse.urlencode(dict(ie='UTF-8',client='gtx',tl='ar',q=text))
            for attempt in range(6):
                try:
                    with urllib.request.urlopen('https://translate.google.com/translate_tts?'+query,timeout=25) as response:
                        payload = response.read()
                        assert response.headers.get('Content-Type','').startswith('audio/') and len(payload)>500
                    raw.write_bytes(payload)
                    break
                except Exception:
                    if attempt==5: raise
                    time.sleep(min(20,2**attempt))
        temporary = target.with_suffix('.part.mp3')
        subprocess.run(['ffmpeg','-nostdin','-y','-v','error','-threads','1','-i',str(raw),
                        '-af','loudnorm=I=-18:TP=-2:LRA=9','-ar','22050','-ac','1',
                        '-c:a','libmp3lame','-b:a','32k','-write_xing','1',str(temporary)],check=True)
        temporary.replace(target)
    probe = json.loads(subprocess.check_output(['ffprobe','-v','error','-show_entries',
                     'format=duration:stream=codec_name','-of','json',str(target)]))
    duration = float(probe['format']['duration'])
    assert .2 < duration < 35, (text,duration)
    assert probe['streams'][0]['codec_name']=='mp3'
    return dict(text=text,path=relative,seconds=round(duration,3),sha256=hashlib.sha256(target.read_bytes()).hexdigest())

clips=[]
with ThreadPoolExecutor(max_workers=args.workers) as pool:
    futures={pool.submit(make,text):text for text in texts}
    for future in as_completed(futures):
        try: clips.append(future.result())
        except Exception as error:
            print('FAILED',futures[future],repr(error),flush=True)
            for pending in futures:pending.cancel()
            raise
        if len(clips)%100==0:print(f'{len(clips)}/{len(texts)} vocabulary recordings verified',flush=True)
clips.sort(key=lambda c:c['text'])
manifest=dict(date=datetime.now(timezone.utc).date().isoformat(),provider='Google Translate TTS (ar); existing verified local lesson recordings reused',
              catalogEntries=sum(len(l['words']) for l in catalog['lists']),clips=clips)
(ROOT/'audio/vocabulary-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
mapping={c['text']:c['path'] for c in clips}
source='''/* Generated by tools/generate-vocabulary-audio.py. Exact NFC keys preserve vowel distinctions. */
(() => { "use strict";
const audio = __MAPPING__;
const api = {audio};
if (typeof module !== "undefined" && module.exports) module.exports = api;
else window.ArabicVocabularyAudio = api;
})();
'''.replace('__MAPPING__',json.dumps(mapping,ensure_ascii=False,separators=(',',':')))
(ROOT/'js/vocab-audio-data.js').write_text(source)
unique={c['path'] for c in clips}
print(f'Complete: {len(clips)} exact words, {sum(p.startswith("audio/vocabulary/") for p in unique)} new MP3s, {sum((ROOT/p).stat().st_size for p in unique):,} audio bytes',flush=True)
