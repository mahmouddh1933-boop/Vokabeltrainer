/* Build the offline exercise catalog and a reviewable map of every supplied photo. */
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const parts = ["a", "b", "c", "d"].map((name) =>
  JSON.parse(
    fs.readFileSync(
      path.join(root, `data/youth-two/part-${name}.json`),
      "utf8",
    ),
  ),
);
const sources = parts
  .flatMap((p) => p.sources)
  .sort((a, b) => a.photo.localeCompare(b.photo));
const activities = parts.flatMap((p) => p.activities);
const existing = [
  "letter-data",
  "practice-data",
  "book-two-data",
  "youth-data",
].reduce(
  (map, name) =>
    Object.assign(
      map,
      require(path.join(root, "js", name + ".js")).audio || {},
    ),
  {},
);
const audio = {};
for (const activity of activities)
  for (const task of activity.tasks) {
    if (!task.audioText) continue;
    const text = task.audioText.normalize("NFC");
    if (!existing[text])
      throw new Error("Missing local listening recording: " + text);
    audio[text] = existing[text];
  }
if (sources.length !== 31 || new Set(sources.map((s) => s.photo)).size !== 31)
  throw new Error("All 31 photos must be covered exactly once");
const payload = JSON.stringify({ sources, activities, audio }, null, 2);
const source = `// Generated by tools/build-youth-two.js. Edit data/youth-two/part-*.json instead.\n(function(root,factory){\n  const data=factory();\n  if(typeof module==="object" && module.exports) module.exports=data;\n  else root.ArabicYouthTwoData=data;\n})(typeof window!=="undefined"?window:globalThis,function(){\n  "use strict";\n  const catalog=${payload};\n  const marks=/[\\u064B-\\u065F\\u0670\\u0640]/g;\n  function normalize(value){\n    return String(value??"").normalize("NFC").replace(marks,"").replace(/[.,،؛؟!?«»“”\"'():]/g," ").replace(/\\s+/g," ").trim();\n  }\n  function ending(value){\n    const text=String(value??"").normalize("NFC").replace(/[\\s.,،؛؟!?«»“”\"'():]+$/g,"");\n    const match=text.match(/[\\u0621-\\u064A]([\\u064B-\\u065F\\u0670]*)$/);\n    const direct=match ? (match[1].match(/[ًٌٍَُِْ]/)?.[0] || "") : "";\n    if(direct) return direct;\n    return text.match(/([ًٌٍَُِْ])ّ?[اى]$/)?.[1] || "";\n  }\n  function joiner(task){ return task.join!==undefined ? task.join : task.joiner!==undefined ? task.joiner : " "; }\n  function isCorrect(task,value){\n    if(task.kind==="open") return false;\n    if(task.kind==="clock") return !!value && Number.isInteger(value.hour) && Number.isInteger(value.minute) && value.hour>=1 && value.hour<=12 && value.hour%12===task.hour%12 && value.minute===task.minute;\n    if(task.kind==="mark") {\n      if(!Array.isArray(value) || new Set(value).size!==value.length) return false;\n      const actual=value.slice().sort((a,b)=>a-b), expected=task.targets.slice().sort((a,b)=>a-b);\n      return actual.length===expected.length && actual.every((v,i)=>Number.isInteger(v)&&v===expected[i]);\n    }\n    if(task.kind==="choice") return String(value??"").normalize("NFC").trim()===task.answer.normalize("NFC").trim();\n    if(task.allowedEnding && ending(value) && !(Array.isArray(task.allowedEnding)?task.allowedEnding:[task.allowedEnding]).includes(ending(value))) return false;\n    return [task.answer,...(task.accepted||[])].some(answer=>normalize(value)===normalize(answer) && (!task.preserveDiacritics || ending(value)===ending(answer)));\n  }\n  return {...catalog,normalize,ending,joiner,isCorrect};\n});\n`;
fs.writeFileSync(path.join(root, "js/youth-two-data.js"), source);
const lines = [
  "# تغطية الصور المرسلة · تدريبات الشباب 2",
  "",
  "جميع الأنشطة والأسئلة مؤلفة للتطبيق على غرار أنماط التدريبات في الصور. الصور الأصلية لا توزع مع التطبيق. أرقام الصور تقابل ترتيب أسماء الملفات الواردة أدناه.",
  "",
  "| الصورة | اسم الملف | صفحة الكتاب | التدريبات المشابهة في التطبيق |",
  "| --- | --- | --- | --- |",
];
for (const s of sources)
  lines.push(
    `| ${s.photo} | ${s.file} | ${s.page || "غير ظاهر"} | ${s.blocks.map((b) => b.title + " (" + b.activity + ")").join("؛ ")} |`,
  );
lines.push(
  "",
  `العدد: ${sources.length} صورة، ${activities.length} نشاطًا، ${activities.reduce((n, a) => n + a.tasks.length, 0)} سؤالًا ومهمة.`,
  "",
  "تقيّم الأسئلة المغلقة وفق المطلوب المحدد. الكتابة والمحادثة المفتوحة لها نماذج وتقييم ذاتي، ولا تحكم الآلة على جميع الصيغ الصحيحة. في كَ/كِ تحفظ الحركة المميزة على الكاف، وتقبل بقية الحركات اختياريا.",
  "",
);
fs.writeFileSync(
  path.join(root, "docs/YOUTH-TWO-COVERAGE.md"),
  lines.join("\n"),
);
console.log(
  `${sources.length} photos → ${activities.length} activities → ${activities.reduce((n, a) => n + a.tasks.length, 0)} tasks; ${Object.keys(audio).length} reused local listening clips`,
);
